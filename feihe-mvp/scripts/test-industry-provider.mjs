import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../lib/industry-provider.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const mod = { exports: {} };
vm.runInNewContext(`(function(module,exports){${code}\n})`, { URL })(mod, mod.exports);
const { parseIndustryNote, fetchIndustryData } = mod.exports;
const options = { projectId: 'sample', spu: 'test product', brand: 'Ours', keywords: ['ignored'], competitorBrands: ['Other'] };
const raw = { noteInfo: { noteId: '1234567890abcdef12345678', title: 'Ours vs Other', favNum: 0 }, brandInfo: { brandName: 'Other' }, userInfo: { nickName: 'Author' } };
const note = parseIndustryNote(raw, options, '2026-10-21T00:00:00Z');
assert.equal(note.brand, 'Other');
assert.equal(note.isOurBrand, false);
assert.equal(note.likedCount, 0);
assert.equal(note.commentCount, null);
assert.equal(note.collectedCount, null);
assert.equal(note.pubTime, null);
assert.equal(note.nature, 'unknown');
assert.equal(parseIndustryNote({ noteInfo: { ...raw.noteInfo, noteId: '../../bad' } }, options, ''), null);
assert.equal(parseIndustryNote({ noteInfo: raw.noteInfo }, options, '').brand, '未识别品牌');
assert.equal(parseIndustryNote({ noteInfo: { ...raw.noteInfo, title: 'unrelated', favNum: '--', cooperNote: 0 } }, options, '').likedCount, null);
let calls = 0;
const result = await fetchIndustryData({ ...options, maxPages: 100, pageSize: 1000 }, async (kw, from, to, pages, project, searchOptions) => {
  calls++; assert.equal(kw, options.spu); assert.equal(pages, 2); assert.equal(searchOptions.pageSize, 60);
  assert.equal(searchOptions.cooperNote, -1); assert.equal(project, options.projectId);
  assert.match(from, /^\d{4}-\d{2}-\d{2}$/); assert.match(to, /^\d{4}-\d{2}-\d{2}$/);
  return { notes: [raw, raw] };
});
assert.equal(calls, 1); assert.equal(result.notes.length, 1); assert.equal(result.liveVerified, true);
const failed = await fetchIndustryData(options, async () => { throw new Error('secret-token'); });
assert.equal(failed.success, false); assert.equal(failed.notes.length, 0); assert(!failed.errorMessage.includes('secret-token'));
const malformed = await fetchIndustryData(options, async () => ({ notes: [{ noteId: 'wrong-protocol' }] }));
assert.equal(malformed.success, false);
const empty = await fetchIndustryData(options, async () => ({ notes: [] }));
assert.equal(empty.success, true); assert.equal(empty.recordCount, 0);
assert(!source.includes('generateOfflineFixtureNotes'));
console.log('Industry provider: real nested protocol, unknown values, safe failure, deduplication and request bounds passed.');
