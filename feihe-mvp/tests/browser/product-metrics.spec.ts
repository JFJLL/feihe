    const metricId = (await created.json()).id;
    await page.goto('/projects/' + projectId + '/metrics');
    await page.getByRole('row').filter({ has: page.getByRole('cell', { name: '待编辑指标', exact: true }) }).getByRole('button', { name: '编辑指标', exact: true }).click();
